-- 应试：导入的读解真题，和每一次交卷。
--
-- 卷面（大题 → 本文 → 小题，连答案）整份存成一个 JSON：只会整份读、整份写，
-- 从来不按某一道题去查，拆成几张表只是平添 join。注音和文章一样用方括号记法。

CREATE TABLE exam (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id       bigint      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    title          text        NOT NULL,
    content        text        NOT NULL,
    question_count integer     NOT NULL,
    -- 有答案的题数。讲义里有的题答案是「—」，不计分
    graded_count   integer     NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_exam_owner ON exam (owner_id);

-- 交一次卷一行。answers 是 {"55": 3, …}，没答的题不在里面。
-- 分数交卷时就算好存下：以后补了卷子的答案，旧成绩不会跟着变。
CREATE TABLE exam_attempt (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id         bigint      NOT NULL REFERENCES exam (id) ON DELETE CASCADE,
    owner_id        bigint      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    answers         text        NOT NULL,
    correct         integer     NOT NULL,
    graded          integer     NOT NULL,
    elapsed_seconds integer     NOT NULL,
    submitted_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_exam_attempt_owner_time ON exam_attempt (owner_id, submitted_at DESC);
CREATE INDEX idx_exam_attempt_exam ON exam_attempt (exam_id);
