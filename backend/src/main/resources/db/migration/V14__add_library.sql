-- 资料：谁都能读的随笔，和要解锁的资料包。
--
-- 内容（包、随笔）只有主人写；用户手里有的是「解锁记录」pack_grant ——
-- 不管钱从哪儿来（支付宝、兑换码、手动送），最后都只往这张表里插一行，
-- 导入卡片、读付费随笔都只认它。换收款渠道不用动资料包本身。

-- 资料包。卡片和日语文章整份存成一个 JSON（PackContent）：只会整份读、整份写，
-- 解锁时复制进用户自己的包和阅读列表，之后怎么改是用户的事。
-- 计数单拎出来：书架要显示，不该为了数卡把整份内容读出来解析。
CREATE TABLE pack (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug          text        NOT NULL UNIQUE,
    title         text        NOT NULL,
    -- 「N5 · 入门」
    level         text        NOT NULL,
    -- 封面上那个大字
    glyph         text        NOT NULL,
    -- 封面的颜色，前端按名字取一组色
    tint          text        NOT NULL CHECK (tint IN ('sakura', 'take', 'ai', 'kin')),
    -- 书架卡片上的一句
    summary       text        NOT NULL,
    -- 详情页的一段
    intro         text        NOT NULL,
    -- DRAFT 只有主人看得见；SOON 上架但还不能买（还在写）；ON_SALE 能买
    status        text        NOT NULL CHECK (status IN ('DRAFT', 'SOON', 'ON_SALE')),
    -- 分。还在写的包可以没有价格
    price_cents   integer CHECK (price_cents > 0),
    -- 还在写的包写一句「预计 12 月」
    note          text,
    content       text        NOT NULL,
    card_count    integer     NOT NULL,
    article_count integer     NOT NULL,
    sort          integer     NOT NULL DEFAULT 0,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_pack_on_sale_priced CHECK (status <> 'ON_SALE' OR price_cents IS NOT NULL)
);

-- 随笔。pack_id 为空的谁都能读（没登录也行），挂在包上的要解锁才能读。
-- 解锁的人读的是这一份，不复制 —— 主人改了、加了新的，买过的人马上看得到。
-- 不和 /self 的 essay 混用：那边的接口谁都能读，混在一起付费内容迟早从那儿漏出去。
CREATE TABLE library_essay (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug         text        NOT NULL UNIQUE,
    pack_id      bigint REFERENCES pack (id) ON DELETE CASCADE,
    title        text        NOT NULL,
    body         text        NOT NULL,
    -- 发出来的日子，读者看到的是它；没发（null）的只有主人看得见
    published_at timestamptz,
    sort         integer     NOT NULL DEFAULT 0,
    updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_library_essay_pack ON library_essay (pack_id);

-- 谁解锁了哪个包。一个人一个包只有一行；一张兑换码、一笔订单也只能用一次。
-- imported_at：付完钱、导入之前关了页面，下次进来还能接着导。
CREATE TABLE pack_grant (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    pack_id     bigint      NOT NULL REFERENCES pack (id) ON DELETE CASCADE,
    source      text        NOT NULL CHECK (source IN ('ALIPAY', 'CODE', 'GIFT')),
    -- 订单号或兑换码；手动送的没有
    ref         text,
    granted_at  timestamptz NOT NULL DEFAULT now(),
    imported_at timestamptz,
    CONSTRAINT uk_grant_user_pack UNIQUE (user_id, pack_id),
    CONSTRAINT uk_grant_source_ref UNIQUE (source, ref)
);

-- 支付宝订单。金额下单时就记下：之后改了价，旧订单还按当时的价核对。
CREATE TABLE pack_order (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    out_trade_no text        NOT NULL UNIQUE,
    user_id      bigint      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    pack_id      bigint      NOT NULL REFERENCES pack (id) ON DELETE CASCADE,
    amount_cents integer     NOT NULL CHECK (amount_cents > 0),
    status       text        NOT NULL CHECK (status IN ('CREATED', 'PAID')),
    -- 支付宝那边的交易号，对账、退款用
    trade_no     text,
    created_at   timestamptz NOT NULL DEFAULT now(),
    paid_at      timestamptz
);

CREATE INDEX idx_pack_order_user ON pack_order (user_id);

-- 兑换码：送人、做活动用。一码一包，用过就记下是谁用的。
CREATE TABLE redeem_code (
    code       text PRIMARY KEY,
    pack_id    bigint      NOT NULL REFERENCES pack (id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    used_by    bigint REFERENCES app_user (id) ON DELETE SET NULL,
    used_at    timestamptz
);
