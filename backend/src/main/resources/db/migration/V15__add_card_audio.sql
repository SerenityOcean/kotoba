-- 卡片自带的录音：Anki 牌组里的发音，导入时一起传上来。一张卡最多两段：单词读音、例句。
-- 只有牌组自带录音的卡才有，没有就不出声 —— 不拿合成语音凑数。
-- 删卡时跟着删（ON DELETE CASCADE），删包、删账号走的都是删卡。

CREATE TABLE card_audio (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id      bigint                      NOT NULL REFERENCES card (id) ON DELETE CASCADE,
    kind         varchar(16)                 NOT NULL CHECK (kind IN ('WORD', 'SENTENCE')),
    content_type varchar(64)                 NOT NULL,
    size_bytes   integer                     NOT NULL,
    data         bytea                       NOT NULL,
    created_at   timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_card_audio_card_kind UNIQUE (card_id, kind)
);

-- 卡片上记一笔有没有：列卡片、复习时据此决定放不放喇叭，不用去碰存录音的表
ALTER TABLE card ADD COLUMN word_audio boolean NOT NULL DEFAULT false;
ALTER TABLE card ADD COLUMN sentence_audio boolean NOT NULL DEFAULT false;
