-- 阅读和应试的「集」：文章、真题多了以后按来源或主题分堆，资料包导入时一包一集。
-- 一个人在同一类（文章 / 真题）下集名不重复；删集不删里面的东西，退回「未归档」（folder_id 为空）。

CREATE TABLE folder (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   bigint      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    kind       text        NOT NULL CHECK (kind IN ('ARTICLE', 'EXAM')),
    name       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_folder_owner_kind_name UNIQUE (owner_id, kind, name)
);

ALTER TABLE article ADD COLUMN folder_id bigint REFERENCES folder (id) ON DELETE SET NULL;
ALTER TABLE exam ADD COLUMN folder_id bigint REFERENCES folder (id) ON DELETE SET NULL;

-- 按集翻页：同一个集里仍是保存时间倒序
CREATE INDEX idx_article_owner_folder_created ON article (owner_id, folder_id, created_at DESC);
CREATE INDEX idx_exam_folder ON exam (folder_id);
