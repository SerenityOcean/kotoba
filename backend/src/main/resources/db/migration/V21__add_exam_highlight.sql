-- 应试：卷面上涂的重点。一段文字（一段本文、一道题的题干、一个选项、解析里的一句）一行，
-- anchor 是前端给这段文字起的名字（b.0.1.3、q.55.s、x.55.reason），这边不解释；
-- ranges 是这段里涂了的几截：[{"start":3,"end":12,"text":"涂上的字","color":1}]，位置按去掉
-- 振り仮名的文字数，color 是第几支笔（1–4）。和难度标记一样跟着卷子走，重做一遍还在；卷子本身分了人，这里不再存 owner。

CREATE TABLE exam_highlight (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id    bigint      NOT NULL REFERENCES exam (id) ON DELETE CASCADE,
    anchor     varchar(40) NOT NULL,
    ranges     text        NOT NULL,
    updated_at timestamptz NOT NULL,
    UNIQUE (exam_id, anchor)
);
